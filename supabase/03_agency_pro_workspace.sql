-- Cada fila pertenece al usuario autenticado que la creó; RLS impide que otras cuentas la lean o modifiquen.

begin;

create table if not exists public.agency_pro_records (
  id bigint generated by default as identity primary key,
  owner_user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  agency_id text not null,
  record_type text not null check (record_type in ('portfolio','followup')),
  record_id text not null,
  payload jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  constraint agency_pro_records_unique unique (owner_user_id, agency_id, record_type, record_id),
  constraint agency_pro_records_payload_object check (jsonb_typeof(payload) = 'object')
);

alter table public.agency_pro_records enable row level security;

drop policy if exists "agency users read own Pro records" on public.agency_pro_records;
create policy "agency users read own Pro records"
  on public.agency_pro_records for select to authenticated
  using (owner_user_id = (select auth.uid()));

drop policy if exists "agency users insert own Pro records" on public.agency_pro_records;
create policy "agency users insert own Pro records"
  on public.agency_pro_records for insert to authenticated
  with check (owner_user_id = (select auth.uid()));

drop policy if exists "agency users update own Pro records" on public.agency_pro_records;
create policy "agency users update own Pro records"
  on public.agency_pro_records for update to authenticated
  using (owner_user_id = (select auth.uid()))
  with check (owner_user_id = (select auth.uid()));

drop policy if exists "agency users delete own Pro records" on public.agency_pro_records;
create policy "agency users delete own Pro records"
  on public.agency_pro_records for delete to authenticated
  using (owner_user_id = (select auth.uid()));

revoke all on public.agency_pro_records from anon;
grant select, insert, update, delete on public.agency_pro_records to authenticated;
grant usage, select on sequence public.agency_pro_records_id_seq to authenticated;

commit;

